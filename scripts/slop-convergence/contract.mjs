/**
 * Frozen contract for the browserless slop-convergence instrument probe.
 *
 * WHAT THIS PROBE ASKS
 *
 * The recorded idea (`.omx/ideas.md`, 2026-07-31) is that "AI slop" is not
 * measurable on a single screen but may be measurable as *convergence* across
 * independent generations of one fixed brief: if N agents given the same brief
 * emit N near-identical screens, that is slop, quantified, with no taste
 * judgment involved.
 *
 * Before spending agent-generation money on that question, one cheaper question
 * has to be answered first:
 *
 *   Can a browserless source-level fingerprint separate a set that was built to
 *   converge from a set that was built to diverge?
 *
 * If it cannot, the convergence idea dies here for the price of one script. That
 * negative result is a valid and useful outcome and must be recorded as-is.
 *
 * WHAT THIS PROBE IS NOT
 *
 * It is not a detector, finding, score, criterion, schema, enum, CLI surface,
 * dependency, or network path. It does not measure real AI generations, does not
 * measure whether a compiled guide pack changes output, and does not rank models
 * or executors. It measures an instrument against controls it constructed
 * itself, which is the weakest possible form of evidence and is only useful for
 * killing a bad instrument early.
 */

