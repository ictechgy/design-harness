export function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

export function canonicalJson(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

/**
 * Deterministic PRNG. Corpus generation must be byte-reproducible so the probe
 * can be re-run and hash-compared without storing fixture files.
 */
export function createRandom(seed) {
  let state = seed >>> 0;
  if (state === 0) state = 0x9e3779b9;
  return function next() {
    state ^= state << 13;
    state >>>= 0;
    state ^= state >>> 17;
    state ^= state << 5;
    state >>>= 0;
    return state / 0x100000000;
  };
}

export function pick(random, values) {
  if (!Array.isArray(values) || values.length === 0) {
    throw new Error("pick requires a non-empty array");
  }
  return values[Math.floor(random() * values.length) % values.length];
}
